#: The curated and extended halves, by the config key that can override
#: them. A lookup searches both, curated half first.
_CURATED_BY_KEY = {
    "gpu_rankings": GPU_CURATED,
    "cpu_rankings": CPU_CURATED,
}
_EXTENDED_BY_KEY = {
    "gpu_rankings": GPU_EXTENDED,
    "cpu_rankings": CPU_EXTENDED,
}


def lookup_table(key: str, config: Any = None) -> list[tuple[tuple[str, float], ...]]:
    """The tables a lookup should search, curated half first.

    A config override replaces the whole table, curated rules and all:
    the user is then the author of the ordering, so the extended half is
    not layered back on top of their table, and the lookup runs over
    their table alone. Without an override the curated half comes first
    and the extended half second, and each is tried in turn -- so a
    longer or more-specific extended pattern can never outrank a curated
    match through a later, more permissive pass, which is the whole
    point of the split.
    """
    curated = _CURATED_BY_KEY[key]
    extended = _EXTENDED_BY_KEY[key]
    if _has_override(key, config):
        return [effective_table(key, curated + extended, config)]
    return [curated, extended]


def _has_override(key: str, config: Any) -> bool:
    """True when *config* carries an override for *key*."""
    if config is None:
        return False
    getter = getattr(config, "get", None)
    if not callable(getter):
        return False
    try:
        return getter(key) is not None
    except Exception:  # noqa: BLE001 - a bad config means "no override"
        return False


def gpu_score(name: str, config: Any = None) -> float | None:
    """The capability score of a GPU name, or ``None`` when unknown.

    ``config``, when given, is anything with a ``get`` method (the app's
    ``Config``); a ``gpu_rankings`` override in it replaces the built-in
    table.
    """
    entry = gpu_entry(name, config)
    return entry[1] if entry else None


def gpu_entry(
    name: str, config: Any = None
) -> tuple[str, float] | None:
    """The matched GPU table entry as ``(pattern, score)``, or ``None``.

    The pattern is the table's spelling of the part, which is what a
    comparison should name: the requirement text may say "NVIDIA GTX
    970 or better", but the table matched "GTX 970".
    """
    return _lookup_entry(name, lookup_table("gpu_rankings", config))


def cpu_score(name: str, config: Any = None) -> float | None:
    """The capability score of a CPU name, or ``None`` when unknown."""
    entry = cpu_entry(name, config)
    return entry[1] if entry else None


def cpu_entry(
    name: str, config: Any = None
) -> tuple[str, float] | None:
    """The matched CPU table entry as ``(pattern, score)``, or ``None``."""
    return _lookup_entry(name, lookup_table("cpu_rankings", config))


def describe(name: str, config: Any = None) -> str | None:
    """A short human label for a GPU or CPU name, or ``None`` if unknown.

    The label names the part itself when the name is a table
    entry (``"GTX 970"`` anchors to the GTX 970, not to the
    first entry at the same score), so it can be checked
    against the tables above instead of trusted on faith. A
    name that only matches by containment ("GTX 970 or
    better") is not a table entry, so it is labelled against
    the nearest anchor at its score. A mobile variant names
    the desktop twin it was matched to, at its discounted
    laptop score. ``config``, when given, is anything with a
    ``get`` method (the app's ``Config``); a ``gpu_rankings``
    or ``cpu_rankings`` override in it replaces the built-in
    table. The GPU table is searched first because GPU names
    are the ones usually asked about.
    """
    for key in ("gpu_rankings", "cpu_rankings"):
        tables = lookup_table(key, config)
        detail = _lookup_detail(name, tables)
        if detail is None:
            continue
        pattern, score, mobile = detail
        table = _containing_table(name, tables)
        if _exact_entry(name, table) is None:
            anchor, _anchor_score = _nearest_anchor(score, table)
        else:
            anchor = pattern
        # A glued mobile marker ("GTX 1080 Max-Q") names the desktop
        # twin, so the twin -- not the nearest entry at the discounted
        # score -- is what the label should read as comparable to.
        if mobile and not _names_a_table_entry(name, table):
            anchor = _desktop_twin(name, table) or anchor
        article = "an" if anchor[:1].lower() in "aeiou" else "a"
        if mobile:
            return (
                f"{tier_word(score)}, ~{score:g}/100 "
                f"({article} {anchor} at laptop clocks)"
            )
        return (
            f"{tier_word(score)}, ~{score:g}/100 "
            f"(comparable to {article} {anchor})"
        )
    return None


def _containing_table(
    name: str, tables: list[tuple[tuple[str, float], ...]]
) -> tuple[tuple[str, float], ...]:
    """The table that supplied the match for *name*, for anchoring.

    ``describe`` anchors a label to the nearest entry at the matched
    score, and the "nearest" should come from the table the match came
    from -- the curated half for a curated entry, so the label reads
    "comparable to a GTX 1060" rather than naming some unrelated
    extended part that happens to sit at the same score.
    """
    for table in tables:
        if _match_table(name, table) is not None:
            return table
    return tables[-1]


def _names_a_table_entry(
    name: str, table: tuple[tuple[str, float], ...]
) -> bool:
    """True when *name* is itself a table entry.

    A glued or spaced mobile marker neither counts against this nor in
    favour of it: "RTX 4080M" and "RTX 4080 M" both name the entry
    "RTX 4080", so a mobile spelling of a table entry is still that
    entry. This is what distinguishes "GTX 970 or better" (prose, which
    anchors to the nearest entry at its score) from a mobile spelling of
    a real entry.
    """
    return _exact_entry(name, table) is not None


def _desktop_twin(
    name: str, table: tuple[tuple[str, float], ...]
) -> str | None:
    """The table entry a mobile spelling of a desktop part resolves to.

    The mobile marker is split off and the remainder looked up, so
    "GTX 1080 Max-Q" and "GTX 1080M" both point at "GTX 1080". A
    spaced marker ("Max-Q") leaves no glued suffix, so the fallback
    compares the leftover tokens against each pattern with the vendor
    words folded away -- which is exactly what the contiguous pass
    did to find the entry in the first place. Only meaningful when the
    name really does carry a mobile marker.
    """
    prepared = _prepared_tokens(name)
    if prepared is None or not prepared[0]:
        return None
    tokens = prepared[1]
    split = _split_glued_mobile(tokens)
    if split is not None:
        tokens = [token for token in split if token != "m"]

    entry = _exact_tokens(tokens, table) if tokens else None
    if entry is not None:
        return entry[0]

    # No exact match: the name carries extra words (a vendor marker, a
    # memory size) that the pattern does not spell out. Find the entry
    # whose tokens are all in the name's, which is the same run that the
    # contiguous pass matched.
    best: tuple[str, float] | None = None
    for pattern, score in table:
        pattern_tokens = list(_tokens(pattern))
        if pattern_tokens and _contains_contiguous(tokens, pattern_tokens):
            if best is None or len(pattern_tokens) > len(_tokens(best[0])):
                best = (pattern, score)
    return best[0] if best else None


def tier_word(score: float) -> str:
    """The capability band of a score: "flagship" ... "low-end"."""
    for threshold, word in _TIERS:
        if score >= threshold:
            return word
    return "low-end"


def tier_text(score: float | None) -> str:
    """The tier as it rides along in a display line.

    Returns ``"mid-range 55/100"`` for a known score and ``"unknown"``
    for ``None`` -- the honest string, not a guessed zero.
    """
    if score is None:
        return UNKNOWN
    return f"{tier_word(score)} {score:g}/100"


